# Codes people write that ISO does not use.
_CODE_ALIASES = {"UK": "GB"}

# Every display name resolves too, including the ones adjusted above.
for _code, _name in NAMES.items():
    _ALIASES.setdefault(_name.lower(), _code)

# The world regions and subregions Upwork filters by (UN M49 names), as slugs.
REGIONS = frozenset({"africa", "americas", "antarctica", "asia", "europe", "oceania"})
SUBREGIONS = frozenset(
    {
        "australia-and-new-zealand", "caribbean", "central-america", "central-asia",
        "eastern-africa", "eastern-asia", "eastern-europe", "melanesia", "micronesia",
        "middle-africa", "northern-africa", "northern-america", "northern-europe",
        "polynesia", "south-america", "south-eastern-asia", "southern-africa",
        "southern-asia", "southern-europe", "western-africa", "western-asia",
        "western-europe",
    }
)
# What people type for the subregions that have a more familiar name.
_AREA_ALIASES = {"north-america": "northern-america", "southeast-asia": "south-eastern-asia"}


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.strip().lower()).strip("-")


def country_code(text: str | None) -> str | None:
    """"Thailand", "thailand", "TH" -> "TH". None when it is not a country."""
    if not text:
        return None
    value = text.strip()
    upper = value.upper()
    if len(value) == 2 and (upper in NAMES or upper in _CODE_ALIASES):
        return _CODE_ALIASES.get(upper, upper)
    return _ALIASES.get(value.lower())


def country_name(code: str | None) -> str | None:
    """"TH" -> "Thailand". Unknown codes come back as given."""
    if not code:
        return None
    upper = _CODE_ALIASES.get(code.strip().upper(), code.strip().upper())
    return NAMES.get(upper, code)


def area(text: str) -> tuple[str, str] | None:
    """("REGION", "europe") or ("SUBREGION", "northern-america"), or None."""
    value = _AREA_ALIASES.get(slug(text), slug(text))
    if value in REGIONS:
        return "REGION", value
    if value in SUBREGIONS:
        return "SUBREGION", value
    return None


def same_country(a: str | None, b: str | None) -> bool:
    """Whether two spellings - names or codes - name the same country."""
    if not a or not b:
        return False
    code_a, code_b = country_code(a), country_code(b)
    if code_a and code_b:
        return code_a == code_b
    return a.strip().lower() == b.strip().lower()
